/**
 * Remove/fix wrongly grouped imports (Aura→Laura, Bakkar→Andora duplicates).
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(process.cwd());
const OUT_TS = path.join(ROOT, 'data', 'leon-products.generated.ts');

function loadProducts() {
  const text = fs.readFileSync(OUT_TS, 'utf8');
  const m = text.match(/export const leonProducts = (\[[\s\S]*\]);/);
  return JSON.parse(m[1]);
}

const REMOVE_GROUP_IDS = new Set(['leon-mg-andora-933']);
const REMOVE_SLUGS = new Set([
  // Aura import pulled Laura colour rows into wrong group
  'laura-perla',
  'laura-crna',
  'laura-zlato-sjaj',
  'laura-bela',
]);

const products = loadProducts();
const before = products.length;

const kept = products.filter((p) => {
  if (REMOVE_GROUP_IDS.has(p.modelGroupId)) return false;
  if (p.modelGroupId === 'leon-mg-aura-4014' && REMOVE_SLUGS.has(p.slug)) return false;
  return true;
});

// Fix modelGroupId on remaining aura rows if any laura left
for (const p of kept) {
  if (p.slug?.startsWith('laura-') && p.modelGroupId === 'leon-mg-aura-4014') {
    delete p.modelGroupId;
  }
}

fs.writeFileSync(
  OUT_TS,
  `/* AUTO-GENERATED by scripts/leon-scrape-explore.mjs + leon-import-missing.mjs */\n` +
    `// No type import here (generated file).\n` +
    `export const leonProducts = ${JSON.stringify(kept, null, 2)};\n`,
  'utf8'
);

console.log(`Removed ${before - kept.length} bad rows. Total: ${kept.length}`);
